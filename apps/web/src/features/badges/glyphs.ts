/** A glyph's lit cells: `[x, y, bright]` for each `#` and `*`. */
export function glyphCells(rows: readonly string[]): [number, number, boolean][] {
  return rows.flatMap((row, y) =>
    [...row].flatMap((c, x): [number, number, boolean][] => (c === '.' ? [] : [[x, y, c === '*']])),
  )
}
