; Behemoth is paper with a huge body: it bombs the place where it will land, then copies itself
; there.
; A process takes the next place along its path, 0x1234 bytes on, and drops a burst of 520 DAT words
; 8 bytes apart over the 4 KB around it, which kills what sits there. Then it writes its body on the
; place with rep movsw, starts a process in the copy, and goes on to the next place.
; Each copy starts its own path at its base with the two bytes swapped, so the copies spread over
; the core, and each one bombs as it goes. A copy takes 1,044 turns, so the bot grows slowly, but a
; copy lands only on ground that it has just bombed.
; The burst is what makes Behemoth a super-heavy: it is 2,047 of its 2,088 bytes, and every copy
; runs it.
; vs imp.asm, seeds 1..20: 14 W / 6 T / 0 L
; vs dwarf.asm, seeds 1..20: 20 W / 0 T / 0 L

%name     "Behemoth"
%author   "ASM Bots"
%strategy "Bomb the next landing place flat, then copy myself onto it"

STEP    equ     0x1234                  ; bytes from one landing place to the next along a path
STRIDE  equ     8                       ; bytes between bombs
BOMBS   equ     520                     ; bombs in a burst
SIZE    equ     end - start
WORDS   equ     SIZE / 2                ; words in a copy
MID     equ     1024 - BOMBS / 2 * STRIDE ; the first bomb, from the landing place

; Setup: the base idiom puts our base address in bx.
start:  call    .here
.here:  pop     bx
        sub     bx, .here

; Grow: a copy starts here with its own base in bx; its path starts at the base, bytes swapped.
grow:   mov     dx, bx
